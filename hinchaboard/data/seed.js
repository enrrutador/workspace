function buildDatabase() {
  const countryName = (code) => {
    const c = COUNTRIES.find((x) => x.code === code);
    return c ? c.name : code;
  };
  const now = new Date().toISOString();
  return {
    createdAt: now,
    countries: COUNTRIES,
    leagues: LEAGUES.map((l) => ({ ...l, countryName: countryName(l.country) })),
    clubs: CLUBS.map(([id, name, country, league, color1, color2]) => ({
      id,
      name,
      country,
      league,
      countryName: countryName(country),
      colors: [color1, color2],
      createdAt: now
    })),
    bids: [],
    messages: [],
    orders: [],
    chatTokens: [],
    chatMessages: []
  };
}

